/* Only the context manager, message operations and their visual integration. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const {spawn, execFileSync} = require('node:child_process');
const {until, connect, killOwned} = require('./browser_smoke.cjs');

(async () => {
  const root = path.resolve(__dirname, '..');
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'nexus-context-browser-'));
  const home = path.join(temporary, 'home'), workspace = path.join(temporary, 'workspace');
  fs.mkdirSync(home); fs.mkdirSync(workspace);
  const pythonPath = process.env.NEXUS_TEST_PYTHON || path.join(root, '.venv/Scripts/python.exe');
  const seen = [];
  let python, chrome, page, browser, output = '', chromeOutput = '';
  const provider = http.createServer(async (req, res) => {
    let raw = ''; for await (const chunk of req) raw += chunk;
    const body = JSON.parse(raw); seen.push(body);
    res.writeHead(200, {'Content-Type': 'text/event-stream'});
    res.end('data: ' + JSON.stringify({choices: [{index: 0, delta: {content: '新的回答 · 测试'}, finish_reason: 'stop'}]}) + '\n\ndata: [DONE]\n\n');
  });
  try {
    await new Promise(resolve => provider.listen(0, '127.0.0.1', resolve));
    fs.writeFileSync(path.join(home, 'config.json'), JSON.stringify({providers: [{id: 'local', name: 'Test', family: 'openai_chat_completions', base_url: `http://127.0.0.1:${provider.address().port}`, models: [{id: 'fake', max_output_tokens: 1024, context_window_tokens: 32000, capabilities: {tools: true}}]}], current: {provider: 'local', model: 'fake'}, permission: 'ask', workspace, effort: 'off'}));
    fs.writeFileSync(path.join(home, 'credentials.json'), JSON.stringify({local: 'test-key'}));
    execFileSync(pythonPath, ['-c', 'import sys\nfrom nexus.application import Application\nfrom nexus.session import Message\na=Application().start(home=sys.argv[1],workspace=sys.argv[2])\ns=a.state["sessions"].load(a.inbox().session_id)\nfor m in [Message("user","早期问题"),Message("assistant","早期回答"),Message("checkpoint","<compacted-summary>历史摘要全文</compacted-summary>",{"through":"1"}),Message("user","近期问题"),Message("assistant","近期回答")]: a.state["sessions"].append(s,m)\na.close()', home, workspace], {cwd: root, windowsHide: true});
    python = spawn(pythonPath, ['-u', '-m', 'nexus', '--home', home, '--workspace', workspace, '--port', '0', '--no-browser'], {cwd: root, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe']});
    python.stdout.on('data', data => output += data); python.stderr.on('data', data => output += data);
    const base = await until(() => {if (python.exitCode !== null) throw Error(output); return output.match(/Nexus: (http:\/\/127\.0\.0\.1:\d+)/)?.[1];}, 'Server startup');
    chrome = spawn(process.env.NEXUS_CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe', ['--headless=new', '--remote-debugging-port=0', '--user-data-dir=' + path.join(temporary, 'chrome'), '--no-first-run', '--no-default-browser-check', 'about:blank'], {windowsHide: true, stdio: ['ignore', 'ignore', 'pipe']});
    chrome.stderr.on('data', data => chromeOutput += data);
    const browserUrl = await until(() => chromeOutput.match(/DevTools listening on (ws:\/\/[^\s]+)/)?.[1], 'Chrome startup');
    browser = await connect(browserUrl);
    const target = await browser.call('Target.createTarget', {url: 'about:blank'});
    const endpoint = new URL(browserUrl); endpoint.protocol = 'http:'; endpoint.pathname = '/json/list';
    const targets = await (await fetch(endpoint)).json();
    page = await connect(targets.find(item => item.id === target.targetId).webSocketDebuggerUrl);
    await page.call('Runtime.enable'); await page.call('Page.enable');
    await page.call('Emulation.setFocusEmulationEnabled', {enabled: true});
    await browser.call('Browser.grantPermissions', {permissions: ['clipboardReadWrite', 'clipboardSanitizedWrite']});
    await page.call('Emulation.setDeviceMetricsOverride', {width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false});
    await page.call('Page.navigate', {url: base});
    await until(() => page.evaluate('typeof lingView!=="undefined" && lingView.items.length===4'), 'Conversation load');
    await page.evaluate('$("context-open").click()');
    await until(() => page.evaluate('!$("context-view").hidden && $("context-view").textContent.includes("所有者指令")'), 'Context page');
    const context = await (await fetch(base + '/api/context')).json();
    assert.equal(context.messages.length, 2);
    assert.equal(context.roles.length, 3);
    // Exercise the shared editor through the real page, including failure and cancellation.
    await page.evaluate('void editText({title:"取消验证",text:"保留内容"});$("edit-input").value="放弃修改";$("edit-cancel").click()');
    assert.equal(await page.evaluate('$("edit-dialog").open'), false);
    await page.evaluate('contextView.nodes.addOwner.click();$("edit-input").value="owner rule";$("edit-form").requestSubmit()');
    await until(() => page.evaluate('!$("edit-dialog").open'), 'Owner save');
    await page.evaluate('contextView.nodes.addOwner.click();$("edit-input").value="第二条";$("edit-form").requestSubmit()');
    await until(() => page.evaluate('!$("edit-dialog").open'), 'Second owner save');
    await page.evaluate('void editText({title:"错误保留",text:"不要丢失",save:async()=>{throw Error("保存失败验证")}});$("edit-form").requestSubmit()');
    await until(() => page.evaluate('$("edit-error").textContent.includes("保存失败验证")'), 'Save failure');
    assert.equal(await page.evaluate('$("edit-input").value'), '不要丢失');
    await page.evaluate('$("edit-cancel").click()');
    assert.equal((await (await fetch(base + '/api/instructions')).json()).text.includes('第二条'), true);
    const roleText = context.roles.find(role => role.id === 'main').text + '\nTEST_ROLE_EDIT';
    await page.evaluate('document.querySelector(".context-role[data-role=main] button").click();$("edit-input").value=' + JSON.stringify(roleText) + ';$("edit-form").requestSubmit()');
    await until(() => page.evaluate('!$("edit-dialog").open'), 'Role save');
    await page.evaluate('selectContextTab("history");contextView.nodes.editSummary.click();$("edit-input").value="手动修改的历史摘要";$("edit-form").requestSubmit()');
    await until(() => page.evaluate('!$("edit-dialog").open'), 'Summary save');
    await page.evaluate('openLing()');
    await page.evaluate('document.querySelectorAll(".msg.user .message-operation")[2].click()');
    await until(() => page.evaluate('$("edit-dialog").open'), 'Resend editor');
    await page.evaluate('$("edit-input").value="重新发送的问题";$("edit-form").requestSubmit()');
    await until(() => page.evaluate('!lingView.running && $("transcript").textContent.includes("新的回答 · 测试")'), 'New model response');
    assert.ok(JSON.stringify(seen[0]).includes('owner rule'));
    assert.ok(JSON.stringify(seen[0]).includes('TEST_ROLE_EDIT'));
    assert.ok(JSON.stringify(seen[0]).includes('手动修改的历史摘要'));
    assert.ok(JSON.stringify(seen[0]).includes('重新发送的问题'));
    assert.ok(!JSON.stringify(seen[0]).includes('近期回答'));
    await page.evaluate('document.querySelector(".msg.assistant:last-child .message-operation").click()');
    await until(() => page.evaluate('$("status").textContent.includes("消息已复制")'), 'Clipboard copy');
    assert.equal(await page.evaluate('navigator.clipboard.readText()'), '新的回答 · 测试');
    await page.evaluate('document.querySelector(".msg.assistant:last-child .message-operation.danger").click();$("edit-form").requestSubmit()');
    await until(() => page.evaluate('!$("edit-dialog").open&&!$("transcript").textContent.includes("新的回答 · 测试")'), 'Delete message');
    await page.evaluate('$("history-undo-button").click()');
    await until(() => page.evaluate('$("transcript").textContent.includes("新的回答 · 测试")'), 'Undo delete');
    const count = seen.length;
    await page.call('Page.reload');
    await until(() => page.evaluate('typeof lingView!=="undefined" && $("transcript").textContent.includes("新的回答 · 测试")'), 'Reload history');
    assert.equal(seen.length, count);
    const artifacts = path.join(root, '.artifacts'); fs.mkdirSync(artifacts, {recursive: true});
    async function screenshot(name) {await new Promise(resolve => setTimeout(resolve, 250)); fs.writeFileSync(path.join(artifacts, name), Buffer.from((await page.call('Page.captureScreenshot', {format: 'png'})).data, 'base64'));}
    await screenshot('context-chat-desktop.png');
    await page.evaluate('$("context-open").click()');
    await until(() => page.evaluate('!$("context-view").hidden&&$("context-view").textContent.includes("owner rule")'), 'Saved context visible');
    await screenshot('context-system-desktop.png');
    await page.evaluate('selectContextTab("history");contextView.nodes.selectAll.click();contextView.nodes.deleteSelected.click();$("edit-form").requestSubmit()');
    await until(() => page.evaluate('!$("edit-dialog").open&&contextView.data.messages.length===0'), 'Context bulk delete');
    await page.evaluate('contextView.nodes.undoButton.click()');
    await until(() => page.evaluate('contextView.data.messages.length===2'), 'Context undo');
    await screenshot('context-history-desktop.png');
    await page.call('Emulation.setDeviceMetricsOverride', {width: 390, height: 844, deviceScaleFactor: 1, mobile: true});
    assert.equal(await page.evaluate('document.documentElement.scrollWidth<=390'), true);
    await screenshot('context-mobile.png');
    await page.call('Emulation.setEmulatedMedia', {features: [{name: 'prefers-reduced-motion', value: 'reduce'}]});
    assert.equal(await page.evaluate('matchMedia("(prefers-reduced-motion: reduce)").matches'), true);
    assert.equal(page.errors.length, 0, JSON.stringify(page.errors));
    console.log('PASS: real context persistence, prompt role/summary/owner effectiveness, message resend/delete/undo/copy, modal cancellation/error drafts, reload without replay, desktop/mobile and reduced motion; local fake provider only.');
  } finally {
    if (page) page.close();
    if (browser) {try {await browser.call('Browser.close');} catch {} browser.close();}
    killOwned(chrome); killOwned(python);
    provider.closeAllConnections(); await new Promise(resolve => provider.close(resolve));
    const resolved = fs.realpathSync(temporary);
    assert.ok(path.dirname(resolved) === fs.realpathSync(os.tmpdir()) && path.basename(resolved).startsWith('nexus-context-browser-'));
    fs.rmSync(resolved, {recursive: true, force: true, maxRetries: 3, retryDelay: 100});
  }
})().catch(error => {console.error(error.stack); process.exitCode = 1;});
